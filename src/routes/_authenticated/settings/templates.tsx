import { useEffect, useState } from "react";
import { createFileRoute } from "@tanstack/react-router";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useCurrentWorkspace } from "@/hooks/use-workspace";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import { toast } from "sonner";
import { Save } from "lucide-react";
import { PageBack, PageBreadcrumbs } from "@/components/page-back";

export const Route = createFileRoute("/_authenticated/settings/templates")({
  head: () => ({ meta: [{ title: "Report templates — Counterpart" }] }),
  component: ReportTemplatesPage,
});

type TemplateConfig = {
  title: string;
  subtitle: string;
  show_top_risks: boolean;
  show_agent_activity: boolean;
  show_evidence_quotes: boolean;
  footer: string;
};

const DEFAULT_CONFIG: TemplateConfig = {
  title: "Contract Risk Review",
  subtitle: "Supplier Offer vs Customer Template",
  show_top_risks: true,
  show_agent_activity: true,
  show_evidence_quotes: true,
  footer: "Generated by Counterpart · Confidential",
};

function ReportTemplatesPage() {
  const qc = useQueryClient();
  const { workspaceId } = useCurrentWorkspace();
  const [busy, setBusy] = useState(false);
  const [name, setName] = useState("Workspace default");
  const [config, setConfig] = useState<TemplateConfig>(DEFAULT_CONFIG);
  const [templateId, setTemplateId] = useState<string | null>(null);

  const { data } = useQuery({
    queryKey: ["report_templates", workspaceId],
    enabled: !!workspaceId,
    queryFn: async () => {
      const { data: rows } = await supabase
        .from("report_templates" as any)
        .select("*")
        .or(`workspace_id.eq.${workspaceId},workspace_id.is.null`)
        .order("is_default", { ascending: false });
      return rows ?? [];
    },
  });

  useEffect(() => {
    if (!data?.length) return;
    const ws = data.find((t: any) => t.workspace_id === workspaceId);
    const pick = ws ?? data.find((t: any) => t.is_default) ?? data[0];
    if (!pick) return;
    setTemplateId(pick.workspace_id ? pick.id : null);
    setName(pick.name ?? "Workspace default");
    setConfig({ ...DEFAULT_CONFIG, ...(pick.config as TemplateConfig) });
  }, [data, workspaceId]);

  const save = async () => {
    if (!workspaceId) return;
    setBusy(true);
    try {
      if (templateId) {
        const { error } = await supabase
          .from("report_templates" as any)
          .update({ name, config, is_default: true, updated_at: new Date().toISOString() })
          .eq("id", templateId);
        if (error) throw error;
      } else {
        const { data: inserted, error } = await supabase
          .from("report_templates" as any)
          .insert({
            workspace_id: workspaceId,
            name,
            is_default: true,
            config,
          })
          .select("id")
          .single();
        if (error) throw error;
        setTemplateId(inserted.id);
      }
      toast.success("Report template saved");
      qc.invalidateQueries({ queryKey: ["report_templates"] });
    } catch (e: any) {
      toast.error(e?.message ?? "Save failed");
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="p-6 lg:p-8 max-w-3xl mx-auto space-y-6">
      <div className="space-y-2">
        <PageBack label="Back to settings" fallback={{ to: "/settings" }} />
        <PageBreadcrumbs items={[{ label: "Settings", to: "/settings" }, { label: "Report templates" }]} />
        <h1 className="text-2xl font-semibold tracking-tight">Report templates</h1>
        <p className="text-sm text-muted-foreground mt-1">
          Configure titles and sections for management PDF reports without changing code.
        </p>
      </div>

      <div className="rounded-xl border bg-card p-5 space-y-4">
        <div className="space-y-1.5">
          <Label>Template name</Label>
          <Input value={name} onChange={(e) => setName(e.target.value)} />
        </div>
        <div className="space-y-1.5">
          <Label>Report title</Label>
          <Input
            value={config.title}
            onChange={(e) => setConfig((c) => ({ ...c, title: e.target.value }))}
          />
        </div>
        <div className="space-y-1.5">
          <Label>Subtitle</Label>
          <Input
            value={config.subtitle}
            onChange={(e) => setConfig((c) => ({ ...c, subtitle: e.target.value }))}
          />
        </div>
        <div className="space-y-1.5">
          <Label>Footer</Label>
          <Input
            value={config.footer}
            onChange={(e) => setConfig((c) => ({ ...c, footer: e.target.value }))}
          />
        </div>

        <div className="space-y-3 pt-2">
          <Toggle
            label="Show top risks"
            checked={config.show_top_risks}
            onChange={(v) => setConfig((c) => ({ ...c, show_top_risks: v }))}
          />
          <Toggle
            label="Show agent activity"
            checked={config.show_agent_activity}
            onChange={(v) => setConfig((c) => ({ ...c, show_agent_activity: v }))}
          />
          <Toggle
            label="Show evidence quotes"
            checked={config.show_evidence_quotes}
            onChange={(v) => setConfig((c) => ({ ...c, show_evidence_quotes: v }))}
          />
        </div>

        <Button onClick={save} disabled={busy}>
          <Save className="w-4 h-4 mr-1.5" />
          {busy ? "Saving…" : "Save template"}
        </Button>
      </div>
    </div>
  );
}

function Toggle({
  label,
  checked,
  onChange,
}: {
  label: string;
  checked: boolean;
  onChange: (v: boolean) => void;
}) {
  return (
    <div className="flex items-center justify-between gap-3">
      <span className="text-sm">{label}</span>
      <Switch checked={checked} onCheckedChange={onChange} />
    </div>
  );
}
